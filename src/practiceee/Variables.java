package practiceee;

public class Variables {
	
	public static void main(String[] args) {
		
		//Variables
		
		
		int a = 7;
		int b = 3;
		int sum = a + b;
		System.out.println("Sum :" + sum);
		int diff = a - b;
		System.out.println("Diff :" + diff);
		int mul = a * b;
		System.out.println("Mul :" + mul);
		int div = a / b;
		System.out.println("Div :" + div);
		int mod = a % b;
		System.out.println("Mod :" + mod);
		
	}	

}
